-- AquaFind database schema (Supabase / PostgreSQL)
-- Applied automatically by the server on every start (CREATE ... IF NOT EXISTS), or paste it into the Supabase SQL Editor.
-- Times are stored as Unix milliseconds (BIGINT), exactly as before.
CREATE TABLE IF NOT EXISTS stations (
  station_id     TEXT PRIMARY KEY,
  station_name   TEXT NOT NULL,
  address        TEXT NOT NULL,
  latitude       DOUBLE PRECISION NOT NULL,
  longitude      DOUBLE PRECISION NOT NULL,
  contact_number TEXT NOT NULL,
  open_hour      INTEGER NOT NULL,   -- 0-23
  close_hour     INTEGER NOT NULL    -- 1-24
);
-- Hours may be unknown (NULL) for stations whose opening hours have not been verified yet.
ALTER TABLE stations ALTER COLUMN open_hour  DROP NOT NULL;
ALTER TABLE stations ALTER COLUMN close_hour DROP NOT NULL;
-- Remembers which one-time data migrations already ran (see migrateRealStations in server.js).
CREATE TABLE IF NOT EXISTS app_migrations (
  migration_key TEXT PRIMARY KEY,
  applied_at    BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS users (
  user_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name     TEXT NOT NULL,
  email         TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  phone         TEXT DEFAULT '',
  avatar        TEXT,                                   -- file name of the profile picture (the image itself is in the avatars table)
  role          TEXT NOT NULL DEFAULT 'user' CHECK (role IN ('user','admin','superadmin')),  -- admin = one station's manager; superadmin = whole system
  station_id    TEXT REFERENCES stations(station_id),  -- only for admins
  alerts_on     INTEGER NOT NULL DEFAULT 1,
  nearby_on     INTEGER NOT NULL DEFAULT 1,
  active        INTEGER NOT NULL DEFAULT 1,             -- 0 = deactivated by a superadmin (cannot sign in)
  created_at    BIGINT NOT NULL
);
-- Every status change adds a row; the newest row is the current status.
CREATE TABLE IF NOT EXISTS availability (
  availability_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  station_id   TEXT NOT NULL REFERENCES stations(station_id),
  status       TEXT NOT NULL CHECK (status IN ('available','low','out','closed')),
  last_updated BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS saved_stations (
  user_id    INTEGER NOT NULL REFERENCES users(user_id),
  station_id TEXT NOT NULL REFERENCES stations(station_id),
  PRIMARY KEY (user_id, station_id)
);
CREATE TABLE IF NOT EXISTS reports (
  report_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  station_id TEXT NOT NULL REFERENCES stations(station_id),
  user_id    INTEGER NOT NULL REFERENCES users(user_id),
  type       TEXT NOT NULL,
  note       TEXT DEFAULT '',
  resolved   INTEGER NOT NULL DEFAULT 0,               -- kept for compatibility: 1 when status = 'resolved'
  created_at BIGINT NOT NULL,
  status     TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected','resolved')),
  admin_note TEXT NOT NULL DEFAULT '',
  updated_at BIGINT
);
-- station_id NULL = general announcement for everyone
CREATE TABLE IF NOT EXISTS notifications (
  notification_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  station_id TEXT REFERENCES stations(station_id),
  title      TEXT NOT NULL,
  body       TEXT NOT NULL,
  created_at BIGINT NOT NULL,
  kind       TEXT NOT NULL DEFAULT 'update'
);
CREATE TABLE IF NOT EXISTS notification_reads (
  user_id INTEGER NOT NULL,
  notification_id INTEGER NOT NULL,
  PRIMARY KEY (user_id, notification_id)
);
-- Community "is there water?" reports from users (separate from official station status)
CREATE TABLE IF NOT EXISTS water_reports (
  wr_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  station_id TEXT NOT NULL REFERENCES stations(station_id),
  user_id    INTEGER NOT NULL REFERENCES users(user_id),
  has_water  INTEGER NOT NULL CHECK (has_water IN (0,1)),
  note       TEXT DEFAULT '',
  created_at BIGINT NOT NULL
);

-- Ratings and reviews: one review per user per station. status 'hidden' = removed from public view by a moderator.
CREATE TABLE IF NOT EXISTS reviews (
  review_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  station_id TEXT NOT NULL REFERENCES stations(station_id),
  user_id    INTEGER NOT NULL REFERENCES users(user_id),
  rating     INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
  comment    TEXT NOT NULL DEFAULT '',
  status     TEXT NOT NULL DEFAULT 'visible' CHECK (status IN ('visible','hidden')),
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL,
  UNIQUE (station_id, user_id)
);
-- Users can flag a review as inappropriate; moderators see flagged reviews first.
CREATE TABLE IF NOT EXISTS review_flags (
  review_id  INTEGER NOT NULL REFERENCES reviews(review_id) ON DELETE CASCADE,
  user_id    INTEGER NOT NULL REFERENCES users(user_id),
  created_at BIGINT NOT NULL,
  PRIMARY KEY (review_id, user_id)
);
-- Profile pictures. Kept in the database (not on a disk) so any host works and backups include them.
CREATE TABLE IF NOT EXISTS avatars (
  file    TEXT PRIMARY KEY,                             -- random file name, the same value as users.avatar
  user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
  mime    TEXT NOT NULL,
  data    BYTEA NOT NULL
);

-- Postgres does not index foreign keys by itself; these keep the common lookups fast.
CREATE INDEX IF NOT EXISTS idx_availability_station ON availability (station_id, availability_id DESC);
CREATE INDEX IF NOT EXISTS idx_reports_station      ON reports (station_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_reports_user         ON reports (user_id);
CREATE INDEX IF NOT EXISTS idx_water_station_time   ON water_reports (station_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_water_time           ON water_reports (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_notifications_time   ON notifications (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_reviews_station      ON reviews (station_id);
CREATE INDEX IF NOT EXISTS idx_reviews_user         ON reviews (user_id);
CREATE INDEX IF NOT EXISTS idx_users_station        ON users (station_id);

-- SECURITY: Supabase publishes every table in the public schema through its REST API, readable with the public "anon" key.
-- Row Level Security with no policies means that API (anon / authenticated roles) can see and change nothing.
-- AquaFind's server connects as the database owner, which is not affected, so the app works as before.
ALTER TABLE stations           ENABLE ROW LEVEL SECURITY;
ALTER TABLE users              ENABLE ROW LEVEL SECURITY;
ALTER TABLE availability       ENABLE ROW LEVEL SECURITY;
ALTER TABLE saved_stations     ENABLE ROW LEVEL SECURITY;
ALTER TABLE reports            ENABLE ROW LEVEL SECURITY;
ALTER TABLE notifications      ENABLE ROW LEVEL SECURITY;
ALTER TABLE notification_reads ENABLE ROW LEVEL SECURITY;
ALTER TABLE water_reports      ENABLE ROW LEVEL SECURITY;
ALTER TABLE reviews            ENABLE ROW LEVEL SECURITY;
ALTER TABLE review_flags       ENABLE ROW LEVEL SECURITY;
ALTER TABLE avatars            ENABLE ROW LEVEL SECURITY;
ALTER TABLE app_migrations     ENABLE ROW LEVEL SECURITY;
-- Belt and braces: also take away the API roles' table privileges (these roles exist on Supabase only).
DO $$
DECLARE t text;
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') AND EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    FOREACH t IN ARRAY ARRAY['stations','users','availability','saved_stations','reports','notifications','notification_reads','water_reports','reviews','review_flags','avatars','app_migrations'] LOOP
      EXECUTE format('REVOKE ALL ON TABLE %I FROM anon, authenticated', t);
    END LOOP;
  END IF;
END $$;

-- Google / Facebook sign-in (Supabase Auth). Accounts that sign in this way have no AquaFind password,
-- so the hash is optional. oauth_identities links one Supabase Auth user to one AquaFind user.
-- Accounts are never merged automatically just because the e-mail address matches.
ALTER TABLE users ALTER COLUMN password_hash DROP NOT NULL;
CREATE TABLE IF NOT EXISTS oauth_identities (
  identity_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supabase_user_id TEXT NOT NULL UNIQUE,
  user_id          INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
  provider         TEXT NOT NULL,
  created_at       BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS oauth_identities_user_idx ON oauth_identities(user_id);